/**
 * Post-build step: writes out/sw.js, a service worker that precaches every
 * file of the static export so the installed web app (e.g. iPhone "Add to
 * Home Screen") opens and works with no network at all.
 *
 * The cache name includes a hash of all file contents, so every new build
 * replaces the old cache atomically on the next online visit.
 */
import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const OUT = path.resolve("out");

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = await Promise.all(entries.map((e) => (e.isDirectory() ? walk(path.join(dir, e.name)) : [path.join(dir, e.name)])));
  return files.flat();
}

const files = (await walk(OUT)).filter((f) => !f.endsWith("sw.js"));
const hash = createHash("sha256");
const urls = [];
for (const f of files.sort()) {
  const rel = "/" + path.relative(OUT, f).split(path.sep).join("/");
  hash.update(rel).update(await readFile(f));
  // Host config files (Netlify/Cloudflare) are not served publicly.
  if (rel === "/_headers" || rel === "/_redirects") continue;
  // The 14 MB OCR engine is cached on first use instead (see OCR_CACHE below).
  if (rel.startsWith("/ocr/")) continue;
  if (rel.endsWith(".html")) {
    // Cache pages only under their canonical "/tasks/" URL: hosts redirect
    // "/tasks/index.html", and Safari rejects redirected service-worker responses.
    if (rel.endsWith("/index.html") && !rel.startsWith("/404/")) urls.push(rel.slice(0, -"index.html".length));
    continue;
  }
  urls.push(rel);
}
const version = hash.digest("hex").slice(0, 12);

const sw = `/* Generated by scripts/generate-sw.mjs — do not edit. */
const CACHE = "uniflow-${version}";
const PRECACHE = ${JSON.stringify([...new Set(urls)])};
// Kept across app updates: the OCR engine only changes with tesseract.js.
const OCR_CACHE = "ocr-tesseract-7";

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith("uniflow-") && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;

  if (url.pathname.startsWith("/ocr/")) {
    event.respondWith((async () => {
      const cache = await caches.open(OCR_CACHE);
      const hit = await cache.match(req, { ignoreSearch: true });
      if (hit) return hit;
      const res = await fetch(req);
      if (res.ok) await cache.put(req, res.clone());
      return res;
    })());
    return;
  }

  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    // Cache-first: every app file is precached, so this works fully offline.
    const hit = await cache.match(req, { ignoreSearch: true });
    if (hit) return hit;
    if (req.mode === "navigate") {
      const p = url.pathname.endsWith("/") ? url.pathname : url.pathname + "/";
      const page = (await cache.match(p)) || (await cache.match(p + "index.html"));
      if (page) return page;
    }
    try {
      return await fetch(req);
    } catch (err) {
      if (req.mode === "navigate") return (await cache.match("/")) || Response.error();
      throw err;
    }
  })());
});
`;
await writeFile(path.join(OUT, "sw.js"), sw);
console.log(`sw.js: precached ${new Set(urls).size} URLs (cache uniflow-${version})`);
